/**
 * Derives the web app's copy of the v3 classifier benchmark from the committed
 * backend artifact.
 *
 * WHY THIS EXISTS: the landing states per-class F1 figures. They were
 * hand-transcribed into `components/landing/ClassF1Bars.tsx`, which is correct
 * today and gated by nothing — if the benchmark moves, the page keeps the old
 * numbers and no check fails. That is the defect shape this repo keeps
 * producing, on a claims surface.
 *
 * WHY NOT READ THE ARTIFACT DIRECTLY: Vercel's root directory for this project
 * is `apps/web`, so `backend/` is not in the deployment bundle. A
 * `readFileSync(process.cwd() + "/../../backend/...")` resolves in a local
 * checkout and throws at request time in production — which is exactly how it
 * failed the first time. A generated file inside the app is bundled; the repo
 * root is not reachable from a serverless function.
 *
 * Run: node scripts/gen-benchmark-facts.mjs [--check]
 *   --check exits non-zero if the committed output is stale, so CI can gate it.
 */
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const SOURCE = path.join(here, "..", "..", "..", "backend", "data", "evaluation", "baseline_hybrid_v3.json");
const OUT = path.join(here, "..", "lib", "benchmark", "baseline-v3.generated.json");

const artifact = JSON.parse(readFileSync(SOURCE, "utf8"));

const derived = {
  _comment: "GENERATED by scripts/gen-benchmark-facts.mjs — do not edit by hand.",
  _source: "backend/data/evaluation/baseline_hybrid_v3.json",
  mode: artifact.meta.mode,
  hybridProfile: artifact.meta.hybrid_profile,
  sampleCount: artifact.meta.sample_count,
  generatedAt: artifact.meta.generated_at,
  // The rules/hybrid baselines carry no dataset_sha256 (only the cascade one
  // does), so this cannot prove which dataset produced it. Stated, not hidden.
  datasetSha256: artifact.meta.dataset_sha256 ?? null,
  macroF1: artifact.overall.macro_f1,
  perLabel: Object.fromEntries(
    Object.entries(artifact.per_label)
      .sort(([a], [b]) => a.localeCompare(b))
      .map(([label, m]) => [label, { f1: m.f1, support: m.support }]),
  ),
};

const serialised = `${JSON.stringify(derived, null, 2)}\n`;

if (process.argv.includes("--check")) {
  let current = null;
  try {
    current = readFileSync(OUT, "utf8");
  } catch {
    console.error(`✗ ${path.relative(process.cwd(), OUT)} is missing — run this script without --check`);
    process.exit(1);
  }
  if (current !== serialised) {
    console.error("✗ the committed benchmark facts are stale against the backend artifact");
    process.exit(1);
  }
  console.log(`✓ benchmark facts agree with ${derived._source} (macro-F1 ${derived.macroF1})`);
} else {
  writeFileSync(OUT, serialised);
  console.log(`wrote ${path.relative(process.cwd(), OUT)} — macro-F1 ${derived.macroF1}, ${Object.keys(derived.perLabel).length} labels`);
}
