export function GoogleSignInButton({
  redirectTo = "/dashboard",
  label = "Continue with Google",
}: {
  /** Same-origin path to land on after the code-exchange. */
  redirectTo?: string;
  label?: string;
}) {
  const [isRedirecting, setIsRedirecting] = useState(false);
  const [error, setError] = useState<string | null>(null);

  async function handleClick() {
    setError(null);
    setIsRedirecting(true);

    // Refuse open redirects: only ever return to a same-origin path.
    const safeRedirect = redirectTo.startsWith("/") ? redirectTo : "/dashboard";
    const callbackUrl = new URL("/callback", window.location.origin);
    callbackUrl.searchParams.set("redirect", safeRedirect);

    const supabase = createClient();
    const { data, error: oauthError } = await supabase.auth.signInWithOAuth({
      provider: "google",
      options: {
        redirectTo: callbackUrl.toString(),
        // Get the URL back instead of navigating — see the file header.
        skipBrowserRedirect: true,
      },
    });

    if (oauthError || !data?.url) {
      setError(NOT_CONFIGURED_MESSAGE);
      setIsRedirecting(false);
      return;
    }

    let response: Response;
    try {
      response = await fetch(data.url, {
        headers: { apikey: publicEnv.NEXT_PUBLIC_SUPABASE_ANON_KEY },
      });
    } catch {
      setError(UNREACHABLE_MESSAGE);
      setIsRedirecting(false);
      return;
    }

    if (!response.ok) {
      // 400 "Unsupported provider: provider is not enabled" lands here.
      setError(NOT_CONFIGURED_MESSAGE);
      setIsRedirecting(false);
      return;
    }

    const payload = (await response.json().catch(() => null)) as {
      url?: string;
    } | null;

    if (!payload?.url) {
      setError(NOT_CONFIGURED_MESSAGE);
      setIsRedirecting(false);
      return;
    }

    // Provider is live — hand the browser to Google's consent screen. Keep the
    // button disabled through the navigation.
    window.location.assign(payload.url);
  }

  return (
    <div className="space-y-2">
      <Button
        type="button"
        variant="outline"
        className="w-full"
        onClick={handleClick}
        disabled={isRedirecting}
      >
        <GoogleGlyph />
        {isRedirecting ? "Connecting…" : label}
      </Button>

      {error ? (
        <p
          role="alert"
          className="rounded-md border border-reject/40 bg-reject/10 px-3 py-2 text-sm text-reject"
        >
          {error}
        </p>
      ) : null}
    </div>
  );
}
