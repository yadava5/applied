"use client";

import { useState } from "react";

import { Button } from "@/components/ui/button";
import { publicEnv } from "@/lib/env";
import { createClient } from "@/lib/supabase/client";

/**
 * "Continue with Google" — Supabase Auth (Google OAuth provider) sign-in.
 *
 * ## Why this isn't a one-liner `signInWithOAuth` call
 *
 * `supabase.auth.signInWithOAuth({ provider: 'google' })` performs **no**
 * network round-trip: it builds the `/auth/v1/authorize` URL client-side and
 * (unless `skipBrowserRedirect` is set) immediately `window.location.assign`s
 * to it — so its returned `error` is always `null`. When the Google provider
 * is **not enabled** on the Supabase project, that endpoint answers `400` with
 * a raw JSON body `{"msg":"Unsupported provider: provider is not enabled"}`
 * and does **not** redirect. Letting the browser navigate there would dump
 * that JSON on the user — a broken-looking dead end.
 *
 * So we ask for the URL **without** redirecting (`skipBrowserRedirect: true`,
 * which also appends `skip_http_redirect=true`, making `/authorize` reply with
 * JSON instead of a 302), pre-flight it with a `fetch`, and only hand the
 * browser off to Google once we've confirmed the provider is live:
 *
 *   - `4xx`            → provider disabled → inline "not configured" message.
 *   - `200 { url }`    → provider live     → `window.location.assign(url)`.
 *   - network failure  → inline "couldn't reach" message.
 *
 * The PKCE `code_verifier` generated by `signInWithOAuth` is persisted by
 * `@supabase/ssr`'s browser client to a **cookie** (not `localStorage`), so
 * the server-side `/callback` route handler can read it to complete
 * `exchangeCodeForSession`. `skipBrowserRedirect` does not change that — the
 * verifier is written when the URL is built — so the deferred navigation here
 * is fully compatible with the existing SSR callback.
 */

const NOT_CONFIGURED_MESSAGE = "Google sign-in isn't configured yet.";
const UNREACHABLE_MESSAGE =
  "Couldn't reach Google sign-in. Check your connection and try again.";

